#!/usr/bin/env bash
# instrument_costs.sh [jobs]
#
# What one strike of each instrument costs: the table kCost in limits.h,
# which the CPU budget (unit.cc) and the step limits (limits.h) count.  Each
# of Brachetti's instruments is struck once on its own, through Braquetti's
# callbacks, and its cost is the mean instructions per frame of the 24
# audio blocks from the strike on (32 ms: the attack, which dense playing
# repeats; a voice costs about that while it sounds), less what the unit
# costs with nothing sounding (its mix and limiter, counted once however
# many instruments play), rounded up to 10.  Counted under qemu-arm as
# cpu_blocks.sh counts them.  Prints the table's rows, then the instruments
# heaviest first.  About 10 minutes with 4 jobs (default: the number of
# processors).
#
# Re-run it when Brachetti's instruments change, and paste the rows into
# limits.h (catalog_test checks that every instrument has a cost).
# Needs: apt-get install g++-arm-linux-gnueabihf qemu-user
set -euo pipefail
here="$(cd "$(dirname "$0")" && pwd)"
unit="$(cd "$here/.." && pwd)"
drum="$(cd "$unit/.." && pwd)"
jobs="${1:-$(nproc)}"
w="$(mktemp -d)"; trap 'rm -rf "$w"' EXIT
ARCH="-march=armv7-a -mtune=cortex-a7 -marm -mfloat-abi=hard -mfpu=neon-vfpv4"
OPT="-Os -pipe -ffast-math -ffp-contract=off -fsigned-char -fno-stack-protector -fstrict-aliasing \
     -falign-functions=16 -fno-math-errno -fomit-frame-pointer -finline-limit=2000000000 \
     --param max-inline-insns-single=2000000000 -ffunction-sections -fdata-sections"
for c in header family_headers; do
    arm-linux-gnueabihf-gcc -c $ARCH $OPT -std=c11 -w -I"$drum/common" "$unit/$c.c" -o "$w/$c.o"
done
arm-linux-gnueabihf-g++ -c $ARCH $OPT -std=gnu++14 -fno-threadsafe-statics -fno-exceptions -fno-rtti -w \
    -I"$drum/common" "$unit/unit.cc" -o "$w/unit.o"
arm-linux-gnueabihf-g++ -c $ARCH -O2 -std=gnu++14 -fno-threadsafe-statics -w -I"$drum/common" \
    "$here/cpu_bench.cpp" -o "$w/bench.o"
arm-linux-gnueabihf-g++ -static $ARCH -Wl,--gc-sections "$w/bench.o" "$w/unit.o" "$w/header.o" \
    "$w/family_headers.o" -lm -o "$w/bench"
arm-linux-gnueabihf-nm "$w/bench" | awk '$3 == "unit_render" { printf "%016s", $1 }' | tr ' ' 0 > "$w/entry"
qemu-arm "$w/bench" names > "$w/names"

# One instrument: family index, program -> "<family> <program> <instructions per frame>"
# (family -1: nothing struck, the unit alone)
cat > "$w/one.sh" <<'EOF'
#!/usr/bin/env bash
set -euo pipefail
w="$1"; f="$2"; p="$3"
entry="$(cat "$w/entry")"
qemu-arm -one-insn-per-tb -d exec,nochain -D /dev/stdout "$w/bench" render "$f" "$p" -1 0 -1 0 0 2048 0 |
    awk -v entry="$entry" -v f="$f" -v p="$p" '
        /^Trace/ { split($0, a, "["); split(a[2], g, "/");
                   if (g[2] == entry) { ++b; if (b >= 3 && b <= 26) { sum += n } n = 0 } ++n }
        END { printf "%d %d %.2f\n", f, p, sum / 24 / 64 }'
EOF
chmod +x "$w/one.sh"
# Block 1 is the reset, block 2 the strike: blocks 2-25 are the 24 measured
# (awk counts block b's instructions when block b+1 starts).
{ echo "-1 0"; awk '{ if ($1 != last) { ++f; last = $1 } print f - 1, $2 }' "$w/names"; } |
    xargs -P "$jobs" -L1 "$w/one.sh" "$w" > "$w/costs"

python3 - "$w/names" "$w/costs" <<'PY'
import sys
names = {}
fams = []
for line in open(sys.argv[1]):
    fam, prog, name = line.rstrip("\n").split(" ", 2)
    if fam not in fams: fams.append(fam)
    names[(fams.index(fam), int(prog))] = name
raw = {}
for line in open(sys.argv[2]):
    f, p, c = line.split()
    raw[(int(f), int(p))] = float(c)
idle = raw.pop((-1, 0))
cost = {k: int(-(-(v - idle) // 10)) * 10 for k, v in raw.items()}   # rounded up to 10
print("    // Generated by test/instrument_costs.sh: one strike, its first 32 ms,")
print("    // less the unit alone (%.0f per frame)." % idle)
for f, fam in enumerate(fams):
    progs = sorted(p for (g, p) in names if g == f)
    vals = ["%4d" % cost[(f, p)] for p in progs]
    rows = [", ".join(vals[i:i + 16]) for i in range(0, len(vals), 16)]
    print("    {%s},  // %s" % (",\n     ".join(rows), fam))
print()
for (f, p), c in sorted(cost.items(), key=lambda kv: -kv[1]):
    print("%5d  %-8s %s" % (c, fams[f], names[(f, p)]))
PY
