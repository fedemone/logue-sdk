#pragma once
// Braquetti — what the CPU allows: what each instrument costs, and the step
// limits built on it (the Policy of seq_core.h; README.md, "When the panel
// shows !!!").
//
// The drumlogue stops a synth unit's audio when it needs too much CPU
// (Brachetti's first ring-over build, at about twice one heavy instrument).
// Braquetti plays up to three families at once, so it counts:
//
//   - kCost: one strike of each instrument, alone, the instructions per
//     frame of its first 32 ms (its attack, which dense playing repeats; a
//     voice costs about that while it sounds), less what the unit costs
//     with nothing sounding.  Measured with test/instrument_costs.sh under
//     qemu-arm: a model to compare cases, not the device's clock.
//   - kCpuBudget: what the live voices may cost together.  The unit counts
//     every live voice at its instrument's cost and, before a strike that
//     would go over, fades older voices (unit.cc).
//   - The step limits: what one step strikes must fit the budget by itself,
//     so the unit never has to fade a hit of the same step to make room for
//     the next.  Checked when a step's instrument is chosen and again when
//     its lane's family changes; what breaks a rule is the instrument just
//     chosen, which shows "!!!" and plays nothing:
//       1. the instruments of one step, across the lanes, cost at most
//          kCpuBudget together;
//       2. a heavy instrument (above kHeavy: the Timpani) plays alone on its
//          step: its strike is the heaviest block the unit renders;
//       3. at most kHeavyRun heavy hits in a row on its lane (the 16 steps
//          loop): four Timpani in a row ran in the hardware test.
#include <cstdint>
#include "seq_core.h"

namespace brq {

constexpr int kCpuBudget = 1800;   // README.md, "CPU": below the ~2,080 known to run
constexpr int kHeavy     = 1200;   // above it, an instrument plays alone on its step
constexpr int kHeavyRun  = 4;      // heavy hits in a row on one lane

constexpr int kCostFamilies = 12;  // Brachetti's families, in brachetti::kFamilies order
constexpr int kCostPrograms = 32;  // the most instruments of a family (Tom)

constexpr uint16_t kCost[kCostFamilies][kCostPrograms] = {
    // Generated by test/instrument_costs.sh: one strike, its first 32 ms,
    // less the unit alone (25 per frame).
    { 510,  360,  360},  // Kick
    { 450,  530,  440,  430,  390,  470,  540,  420,  420,  490,  390,  400,  430,  390,  400,  400,
      400,  430,  430,  360,  490,  470,  430,  490,  420,  420,  470,  470,  490,  490,  420,  440},  // Tom
    {1530,  560},  // Kernel
    { 500,  420,  480,  450,  450,  450,  450,  450},  // Snare
    { 350,  350,  380,  320,  350,  410,  350,  380,  350,  350,  380,  380,  380,  380,  380,  380,
      370,  350,  350},  // Bar
    { 480,  480,  450,  470,  450,  450,  470},  // Plate
    { 660, 1000,  610,  640,  640,  610},  // Cymbal
    { 300,  290,  250,  300,  290,  290,  240,  300},  // Noise
    { 400,  390,  390,  410,  390,  810,  810,  480,  380},  // World
    { 450,  460,  460,  510,  530,  510,  510,  450},  // Lippa
    { 390,  390,  410,  400,  400},  // Pizzico
    { 490,  500,  470,  540,  390,  520,  420},  // Cordiera
};

// The cost of a step code (program + 1; 0: nothing).  An instrument the
// table does not have (Brachetti grew; catalog_test fails until it is
// measured) counts as the whole budget: it plays alone.
inline int cost(int family, int code) {
    if (code <= 0) return 0;
    if (family < 0 || family >= kCostFamilies || code > kCostPrograms) return kCpuBudget;
    const int c = kCost[family][code - 1];
    return c ? c : kCpuBudget;
}

inline bool heavy(int family, int code) { return cost(family, code) > kHeavy; }

// The Policy (seq_core.h): may <lane> play <code> of <family> on <step>,
// given what the lanes hold now?  The families are Brachetti's indices.
struct CpuLimits {
    template <class Seq>
    static bool allows(const Seq& seq, int lane, int step, int family, int code) {
        const bool is_heavy = heavy(family, code);
        int sum = cost(family, code);
        for (int l = 0; l < kLanes; ++l) {
           const int other = seq.step(l, step);
           if (l == lane || !other) continue;
           if (is_heavy || heavy(seq.family(l), other)) return false;     // rule 2
           sum += cost(seq.family(l), other);
        }
        if (sum > kCpuBudget) return false;                                // rule 1
        if (!is_heavy) return true;
        const int n = kSteps;                                              // rule 3
        int run = 1;
        for (int k = 1; k < n && heavy(family, seq.step(lane, (step + k) % n)); ++k) ++run;
        for (int k = 1; k < n && heavy(family, seq.step(lane, (step + n - k) % n)); ++k) ++run;
        return run <= kHeavyRun;
    }
};

}  // namespace brq
